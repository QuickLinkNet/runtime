import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dist = join(root, 'dist');

async function walk(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else files.push(path);
  }
  return files;
}

const allFiles = await walk(dist);
const precacheFiles = allFiles.filter((path) => {
  const name = relative(dist, path).replaceAll('\\', '/');
  return name === 'index.html'
    || name === 'offline.html'
    || name === 'manifest.webmanifest'
    || name.startsWith('assets/')
    || name.startsWith('runtime-icon')
    || name === 'apple-touch-icon.png';
});
const digest = createHash('sha256');
for (const path of precacheFiles) digest.update(await readFile(path));
const version = digest.digest('hex').slice(0, 12);
const precache = precacheFiles.map((path) => `./${relative(dist, path).replaceAll('\\', '/')}`);

const source = `/* Generated by scripts/build-sw.mjs. */
const VERSION = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};
const SHELL_CACHE = \`runtime-shell-\${VERSION}\`;
const ASSET_CACHE = 'runtime-assets-v1';
const ART_CACHE = 'runtime-card-art-v1';

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL_CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith('runtime-shell-') && name !== SHELL_CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

async function trimCache(cacheName, maximum) {
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  await Promise.all(keys.slice(0, Math.max(0, keys.length - maximum)).map((key) => cache.delete(key)));
}

async function networkFirst(request) {
  try {
    const response = await fetch(request);
    if (response.ok) (await caches.open(SHELL_CACHE)).put(request, response.clone());
    return response;
  } catch {
    return (await caches.match(request))
      || (await caches.match(new URL('./index.html', self.registration.scope)))
      || (await caches.match(new URL('./offline.html', self.registration.scope)));
  }
}

async function cacheFirst(request, cacheName, maximum) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(cacheName);
    await cache.put(request, response.clone());
    if (maximum) await trimCache(cacheName, maximum);
  }
  return response;
}

async function staleWhileRevalidate(request, cacheName, maximum) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  const fresh = fetch(request).then(async (response) => {
    if (response.ok) {
      await cache.put(request, response.clone());
      if (maximum) await trimCache(cacheName, maximum);
    }
    return response;
  }).catch(() => cached);
  return cached || fresh;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.includes('/api/')) return;
  if (request.mode === 'navigate') {
    event.respondWith(networkFirst(request));
    return;
  }
  if (url.pathname.includes('/card-assets/')) {
    event.respondWith(staleWhileRevalidate(request, ART_CACHE, 80));
    return;
  }
  if (['style', 'script', 'image', 'font'].includes(request.destination)) {
    event.respondWith(cacheFirst(request, ASSET_CACHE, 160));
  }
});
`;

await writeFile(join(dist, 'sw.js'), source, 'utf8');
console.log(`Service Worker ${version}: ${precache.length} App-Shell-Dateien vorgeladen.`);
